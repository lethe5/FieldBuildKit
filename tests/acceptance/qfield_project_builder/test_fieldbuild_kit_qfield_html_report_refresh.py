def _direct_tables(layers: list[dict[str, Any]]) -> list[dict[str, Any]]:
    """Translate QGIS feature mocks to unclassified direct GeoPackage SQL rows."""
    tables = []
    for layer in layers:
        rows = []
        for feature in layer["features"]:
            row = dict(feature["attributes"])
            geometry = feature.get("geometry")
            if layer["geometry_column"] is not None:
                row[layer["geometry_column"]] = (
                    None
                    if geometry is None or geometry.get("isNull") or geometry.get("isEmpty")
                    else geometry.get("asJson", {}).get("return", "invalid-wkb")
                )
            rows.append(row)
        columns = list(layer["fields"])
        if layer["geometry_column"] is not None:
            columns.append(layer["geometry_column"])
        tables.append({
            "name": layer["name"], "columns": columns,
            "geometry_column": layer["geometry_column"], "geometry_type": layer["geometry_type"],
            "srs_id": layer["crs_authid"], "rows": rows,
        })
    return tables


