def _run(renderer, fixture: dict[str, Any]) -> dict[str, Any]:
    # These names identify the retired abstract/Python-model fixture contract. A bridge that
    # accepts them can silently avoid exercising the QML provider reads and generated HTML.
    forbidden = {"source_columns", "source_rows", "spatial_records", "anchor_contexts", "analytics_input"}
    assert not (forbidden & fixture.keys())
    original = copy.deepcopy(fixture)
    result = renderer(fixture)
    assert fixture == original, "QGIS collection and report rendering must be read-only"
    assert result["success"] is True, result.get("error_message")
    assert result["bridge"]["qml"]["qpb_build_html_report_called"] is True
    assert result["bridge"]["html"]["generated_from_qpb_build_html_report"] is True
    return result


def _payload(result: dict[str, Any]) -> dict[str, Any]:
    """The actual qpbLastReportPayload, serialized by the QML runtime after collection."""
    return result["bridge"]["qml"]["report_payload"]


def _html(result: dict[str, Any]) -> dict[str, Any]:
    """DOM observations from the scripts embedded in that exact generated HTML."""
    return result["bridge"]["html"]["document"]


def _geometry_by_uuid(result: dict[str, Any]) -> dict[str, dict[str, Any]]:
    records: dict[str, dict[str, Any]] = {}
    for table in _payload(result)["tables"]:
        for record in table.get("records", []):
            records[str(record["uuid"])] = record["geometry"]
    return records


def _coordinate_vectors(geometry: Any) -> Iterable[list[Any]]:
    if isinstance(geometry, dict):
        if "coordinates" in geometry:
            yield from _coordinate_vectors(geometry["coordinates"])
        for key, value in geometry.items():
            if key != "coordinates":
                yield from _coordinate_vectors(value)
    elif isinstance(geometry, list):
        if geometry and all(not isinstance(value, (dict, list)) for value in geometry):
            yield geometry
        else:
            for value in geometry:
                yield from _coordinate_vectors(value)


def _assert_xy_only(geometry: dict[str, Any]) -> None:
    vectors = list(_coordinate_vectors(geometry))
    assert vectors, "valid GeoJSON must contain coordinate vectors"
    assert all(len(vector) == 2 for vector in vectors), geometry


def _feature(attributes: dict[str, Any], geometry: dict[str, Any] | None) -> dict[str, Any]:
    """A QGIS feature mock: attributes plus a runtime QgsGeometry-method descriptor."""
    return {"attributes": attributes, "geometry": geometry}


def _layer(
    name: str,
    fields: list[str],
    features: list[dict[str, Any]],
    *,
    geometry_column: str | None = None,
    geometry_type: str | None = None,
    crs: str = "EPSG:4326",
) -> dict[str, Any]:
    return {
        "name": name,
        "fields": fields,
        "geometry_column": geometry_column,
        "geometry_type": geometry_type,
        "crs_authid": crs,
        "features": features,
    }


